#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 page/vendor/heic2any.min.js 固化成 src/heic_js.h（改了解码器必跑）。

输出符号：
    static const unsigned char heic_js_gz[]    = { ... };
    static const unsigned int  heic_js_gz_len  = NNN;
    static const unsigned int  heic_js_raw_len = MMM;

设计要点：
    * 页面不内嵌这份 JS，固件用独立路由 GET /heic2any.js 按需发出，
      避免主页面 gzip 从 ~70 KB 暴涨、重演大响应吃光堆的问题。
    * gzip 用 mtime=0 保证同样输入永远同样输出，便于比对。
    * 硬上限 400 KB：ota 槽 1408 KB，当前 app 928 KB，留足余量；
      真超了直接失败，不要让链接器在最后一步才报模糊错误。
"""
import gzip
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "page", "vendor", "heic2any.min.js")
DST = os.path.join(ROOT, "src", "heic_js.h")

MAX_GZ = 400 * 1024


def main():
    if not os.path.isfile(SRC):
        print("!! 缺少解码器：%s" % SRC)
        return 1

    data = open(SRC, "rb").read()
    text = data.decode("utf-8", "ignore")
    if "heic2any" not in text or len(data) < 100000:
        print("!! %s 不像 heic2any 的构建产物" % SRC)
        return 1

    gz = gzip.compress(data, 9, mtime=0)
    if len(gz) > MAX_GZ:
        print("!! 解码器 gzip 后 %d B，超过上限 %d B，拒绝生成" % (len(gz), MAX_GZ))
        return 1

    lines = []
    lines.append("/* auto-generated by tools/make_heic_header.py - do not edit */")
    lines.append("/* page/vendor/heic2any.min.js %d B -> gzip %d B (%.0f%%) */"
                 % (len(data), len(gz), len(gz) * 100.0 / len(data)))
    lines.append("static const unsigned char heic_js_gz[] = {")
    for i in range(0, len(gz), 16):
        chunk = gz[i:i + 16]
        lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("static const unsigned int heic_js_gz_len  = %d;" % len(gz))
    lines.append("static const unsigned int heic_js_raw_len = %d;" % len(data))
    lines.append("")

    open(DST, "w", encoding="ascii", newline="\n").write("\n".join(lines))
    print("wrote %s (%d B -> gzip %d B) -> %s" % (SRC, len(data), len(gz), DST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
